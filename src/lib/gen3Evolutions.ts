export function evolutionOptions(speciesId: number): EvolutionRule[] {
  // Shedinja es un resultado adicional, no un reemplazo de Nincada.
  return GEN3_EVOLUTIONS.filter(
    (r) => r.from === speciesId && r.method !== "level_shedinja",
  );
}
export function findEvolution(
  from: number,
  to: number,
): EvolutionRule | undefined {
  return evolutionOptions(from).find((r) => r.to === to);
}
